// Emits src/journeyman-embed.ts from JOURNEYMAN.md so GET /journeyman can
// serve the traveling worker's standing instructions verbatim out of the
// Worker bundle (same approach as arena-data and the steward / ambassador
// embeds, no external fetch, works even though the runner repo
// ergonia-journeyman is private).
//
//   node scripts/gen-journeyman-embed.mjs           regenerate
//   node scripts/gen-journeyman-embed.mjs --check   exit 1 if the embed is
//                                                   stale vs JOURNEYMAN.md
//
// The content is emitted with JSON.stringify, so every backtick, dollar
// sign and backslash in the source survives untouched. "Verbatim" is the
// whole point: the file is a public promise, and a promise that drifts
// from what is served is worse than no promise.
//
// The source of truth here is JOURNEYMAN.md at THIS repo's root. It is
// kept in sync by hand with ergonia-journeyman/JOURNEYMAN.md, the copy
// the traveling worker actually runs against; the two files must match
// byte for byte and the operator's checklist enforces that on every
// constitution edit.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const SOURCE = resolve(ROOT, "JOURNEYMAN.md");
const TARGET = resolve(ROOT, "src", "journeyman-embed.ts");

const body = readFileSync(SOURCE, "utf8");

const out = `// AUTOGENERATED by scripts/gen-journeyman-embed.mjs, do not edit.
// Source of truth: JOURNEYMAN.md at the repository root.
//
// Regenerate with:  node scripts/gen-journeyman-embed.mjs
// Verify freshness: node scripts/gen-journeyman-embed.mjs --check

export const JOURNEYMAN_MD: string = ${JSON.stringify(body)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(TARGET, "utf8");
  } catch {
    console.error("FAIL: src/journeyman-embed.ts is missing. Run: node scripts/gen-journeyman-embed.mjs");
    process.exit(1);
  }
  if (current !== out) {
    console.error("FAIL: src/journeyman-embed.ts is stale vs JOURNEYMAN.md.");
    console.error("      Run: node scripts/gen-journeyman-embed.mjs");
    process.exit(1);
  }
  console.log("OK: src/journeyman-embed.ts matches JOURNEYMAN.md byte for byte.");
  process.exit(0);
}

writeFileSync(TARGET, out, { encoding: "utf8" });
console.log(`wrote src/journeyman-embed.ts (${body.length} bytes of JOURNEYMAN.md embedded)`);
