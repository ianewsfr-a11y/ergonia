// Emits src/steward-embed.ts from STEWARD.md so GET /steward can serve
// the steward's standing instructions verbatim out of the Worker bundle
// (same approach as arena-data — no external fetch, works even though the
// source repo is private).
//
//   node scripts/gen-steward-embed.mjs           regenerate
//   node scripts/gen-steward-embed.mjs --check   exit 1 if the embed is
//                                                stale vs STEWARD.md
//
// The content is emitted with JSON.stringify, so every backtick, dollar
// sign and backslash in the source survives untouched. "Verbatim" is the
// whole point: the file is a public promise, and a promise that drifts
// from what is served is worse than no promise.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const SOURCE = resolve(ROOT, "STEWARD.md");
const TARGET = resolve(ROOT, "src", "steward-embed.ts");

const body = readFileSync(SOURCE, "utf8");

const out = `// AUTOGENERATED by scripts/gen-steward-embed.mjs — do not edit.
// Source of truth: STEWARD.md at the repository root.
//
// Regenerate with:  node scripts/gen-steward-embed.mjs
// Verify freshness: node scripts/gen-steward-embed.mjs --check

export const STEWARD_MD: string = ${JSON.stringify(body)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(TARGET, "utf8");
  } catch {
    console.error("FAIL: src/steward-embed.ts is missing. Run: node scripts/gen-steward-embed.mjs");
    process.exit(1);
  }
  if (current !== out) {
    console.error("FAIL: src/steward-embed.ts is stale vs STEWARD.md.");
    console.error("      Run: node scripts/gen-steward-embed.mjs");
    process.exit(1);
  }
  console.log("OK: src/steward-embed.ts matches STEWARD.md byte for byte.");
  process.exit(0);
}

writeFileSync(TARGET, out, { encoding: "utf8" });
console.log(`wrote src/steward-embed.ts (${body.length} bytes of STEWARD.md embedded)`);
