// Emits src/ambassador-embed.ts from AMBASSADOR.md so GET /ambassador can
// serve the ambassador's standing instructions verbatim out of the Worker
// bundle (same approach as arena-data and the steward embed — no external
// fetch, works even though the source repo the agent runs in is private).
//
//   node scripts/gen-ambassador-embed.mjs           regenerate
//   node scripts/gen-ambassador-embed.mjs --check   exit 1 if the embed is
//                                                   stale vs AMBASSADOR.md
//
// The content is emitted with JSON.stringify, so every backtick, dollar
// sign and backslash in the source survives untouched. "Verbatim" is the
// whole point: the file is a public promise, and a promise that drifts
// from what is served is worse than no promise.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const SOURCE = resolve(ROOT, "AMBASSADOR.md");
const TARGET = resolve(ROOT, "src", "ambassador-embed.ts");

const body = readFileSync(SOURCE, "utf8");

const out = `// AUTOGENERATED by scripts/gen-ambassador-embed.mjs — do not edit.
// Source of truth: AMBASSADOR.md at the repository root.
//
// Regenerate with:  node scripts/gen-ambassador-embed.mjs
// Verify freshness: node scripts/gen-ambassador-embed.mjs --check

export const AMBASSADOR_MD: string = ${JSON.stringify(body)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(TARGET, "utf8");
  } catch {
    console.error("FAIL: src/ambassador-embed.ts is missing. Run: node scripts/gen-ambassador-embed.mjs");
    process.exit(1);
  }
  if (current !== out) {
    console.error("FAIL: src/ambassador-embed.ts is stale vs AMBASSADOR.md.");
    console.error("      Run: node scripts/gen-ambassador-embed.mjs");
    process.exit(1);
  }
  console.log("OK: src/ambassador-embed.ts matches AMBASSADOR.md byte for byte.");
  process.exit(0);
}

writeFileSync(TARGET, out, { encoding: "utf8" });
console.log(`wrote src/ambassador-embed.ts (${body.length} bytes of AMBASSADOR.md embedded)`);
